import { WorkflowNode, NodeConnection } from '../types/workflow';

export interface AiAgentOptions {
  prompt: string;
  provider?: 'openrouter' | 'ollama' | 'gemini' | 'openai' | 'anthropic' | 'laya' | 'built-in';
  apiKey?: string;
  customEndpoint?: string;
  baseUrl?: string;
}

export interface AiAgentResult {
  workflowName: string;
  nodes: WorkflowNode[];
  connections: NodeConnection[];
  summary: string;
}

export async function generateLoadTestFromAiPrompt(options: AiAgentOptions): Promise<AiAgentResult> {
  const { prompt, provider = 'built-in', apiKey, baseUrl = 'https://api.example.com' } = options;

  // Try API call if external provider and key/endpoint is set
  if (provider !== 'built-in' && (apiKey || provider === 'ollama' || provider === 'laya')) {
    try {
      const apiResult = await callExternalAiApi(options);
      if (apiResult) return apiResult;
    } catch (err) {
      console.warn('External AI API call failed, falling back to intelligent built-in agent:', err);
    }
  }

  // Fallback / Built-in Intelligent NLP Agent
  return parsePromptToIntelligentTopology(prompt, baseUrl);
}

async function callExternalAiApi(options: AiAgentOptions): Promise<AiAgentResult | null> {
  const { prompt, provider, apiKey, customEndpoint, baseUrl = 'https://api.example.com' } = options;

  const systemInstruction = `
You are a DevOps and Load Testing AI Agent.
Analyze the user's load test scenario prompt and reply ONLY with valid JSON in this structure:
{
  "workflowName": "string",
  "summary": "string",
  "virtualUsers": number,
  "rampUpSeconds": number,
  "durationSeconds": number,
  "maxP95LatencyMs": number,
  "maxErrorPercentage": number,
  "endpoints": [
    {
      "title": "string",
      "method": "GET" | "POST" | "PUT" | "DELETE",
      "path": "string",
      "body": "string",
      "thinkTimeMs": number
    }
  ]
}
Do not wrap in markdown or code block.
`;

  let responseText = '';

  if (provider === 'laya') {
    const url = customEndpoint || 'http://localhost:8000/v1/systemone';
    const res = await fetch(url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        ...(apiKey ? { 'Authorization': `Bearer ${apiKey}` } : {})
      },
      body: JSON.stringify({
        state: { body: prompt },
        questions: {
          scenario: {
            type: "choice",
            instructions: "Determine scenario complexity",
            criteria: { "high": "heavy load", "normal": "standard load" }
          }
        }
      })
    });
    if (!res.ok) return null;
    const data = await res.json();
    if (data) {
      return parsePromptToIntelligentTopology(prompt, baseUrl);
    }
  } else if (provider === 'ollama') {
    const url = customEndpoint || 'http://localhost:11434/api/generate';
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: 'llama3',
        prompt: `${systemInstruction}\nUser Prompt: ${prompt}`,
        stream: false
      })
    });
    const data = await res.json();
    responseText = data.response;
  } else if (provider === 'openai' || provider === 'openrouter') {
    const url = provider === 'openrouter'
      ? 'https://openrouter.ai/api/v1/chat/completions'
      : 'https://api.openai.com/v1/chat/completions';

    const res = await fetch(url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${apiKey}`
      },
      body: JSON.stringify({
        model: provider === 'openrouter' ? 'meta-llama/llama-3.1-70b-instruct:free' : 'gpt-4o-mini',
        messages: [
          { role: 'system', content: systemInstruction },
          { role: 'user', content: prompt }
        ],
        temperature: 0.2
      })
    });
    const data = await res.json();
    responseText = data.choices?.[0]?.message?.content || '';
  }

  if (!responseText) return null;

  try {
    const jsonMatch = responseText.match(/\{[\s\S]*\}/);
    if (!jsonMatch) return null;
    const parsed = JSON.parse(jsonMatch[0]);

    return convertParsedJsonToWorkflow(parsed, baseUrl);
  } catch {
    return null;
  }
}

function convertParsedJsonToWorkflow(parsed: any, baseUrl: string): AiAgentResult {
  const workflowName = parsed.workflowName || 'AI Designed Load Scenario';
  const summary = parsed.summary || 'Custom load test generated by AI Agent';

  const targetId = `node-${Date.now()}-target`;
  const trafficId = `node-${Date.now()}-traffic`;
  const slaId = `node-${Date.now()}-sla`;

  const nodes: WorkflowNode[] = [
    {
      id: targetId,
      type: 'target_server',
      title: 'Target Web Service',
      subtitle: baseUrl,
      category: 'Target Server',
      x: 100,
      y: 80,
      iconType: 'server',
      badge: 'Endpoint Ingress',
      badgeColor: 'bg-emerald-500/20 text-emerald-300 border-emerald-500/30',
      config: { baseUrl }
    },
    {
      id: trafficId,
      type: 'traffic_profile',
      title: 'Traffic & Ramping',
      subtitle: `${parsed.virtualUsers || 50} VUsers | ${parsed.durationSeconds || 30}s`,
      category: 'Traffic Profile',
      x: 100,
      y: 240,
      iconType: 'users',
      badge: 'Concurrency Engine',
      badgeColor: 'bg-amber-500/20 text-amber-300 border-amber-500/30',
      config: {
        virtualUsers: parsed.virtualUsers || 50,
        rampUpSeconds: parsed.rampUpSeconds || 5,
        durationSeconds: parsed.durationSeconds || 30
      }
    }
  ];

  const connections: NodeConnection[] = [
    { id: `conn-1`, fromNodeId: targetId, toNodeId: trafficId }
  ];

  let lastNodeId = trafficId;
  let currentY = 400;

  const endpoints = Array.isArray(parsed.endpoints) ? parsed.endpoints : [
    { title: 'User Login', method: 'POST', path: '/api/v1/auth/login', body: '{"username":"test","password":"secret"}' },
    { title: 'Fetch User Profile', method: 'GET', path: '/api/v1/users/me' },
    { title: 'Search Jobs Catalog', method: 'GET', path: '/api/v1/jobs?limit=20' }
  ];

  endpoints.forEach((ep: any, index: number) => {
    const reqId = `node-${Date.now()}-req-${index}`;
    nodes.push({
      id: reqId,
      type: 'http_request',
      title: ep.title || `Request ${index + 1}`,
      subtitle: `${ep.method || 'GET'} ${ep.path || '/'}`,
      category: 'User Journey',
      x: 100,
      y: currentY,
      iconType: 'globe',
      badge: 'HTTP Action',
      badgeColor: 'bg-blue-500/20 text-blue-300 border-blue-500/30',
      config: {
        httpMethod: ep.method || 'GET',
        endpointPath: ep.path || '/',
        body: ep.body || '',
        thinkTimeMs: ep.thinkTimeMs || 100
      }
    });

    connections.push({
      id: `conn-req-${index}`,
      fromNodeId: lastNodeId,
      toNodeId: reqId
    });

    lastNodeId = reqId;
    currentY += 160;
  });

  nodes.push({
    id: slaId,
    type: 'sla_assertion',
    title: 'SLA Quality Gate',
    subtitle: `p95 < ${parsed.maxP95LatencyMs || 500}ms | Error < ${parsed.maxErrorPercentage || 2.0}%`,
    category: 'SLA & Assertions',
    x: 100,
    y: currentY,
    iconType: 'shield',
    badge: 'Quality Gate',
    badgeColor: 'bg-purple-500/20 text-purple-300 border-purple-500/30',
    config: {
      maxP95LatencyMs: parsed.maxP95LatencyMs || 500,
      maxErrorPercentage: parsed.maxErrorPercentage || 2.0
    }
  });

  connections.push({
    id: `conn-sla`,
    fromNodeId: lastNodeId,
    toNodeId: slaId
  });

  return {
    workflowName,
    nodes,
    connections,
    summary
  };
}

function parsePromptToIntelligentTopology(prompt: string, baseUrl: string): AiAgentResult {
  const lower = prompt.toLowerCase();

  let virtualUsers = 50;
  let durationSeconds = 30;
  let rampUpSeconds = 5;

  // Extract concurrency from prompt numbers
  const vuserMatch = prompt.match(/(\d+)\s*(virtual\s*users|users|vusers|concurrency|concurrent)/i);
  if (vuserMatch) virtualUsers = parseInt(vuserMatch[1], 10);

  const durationMatch = prompt.match(/(\d+)\s*(seconds|sec|s|minutes|min)/i);
  if (durationMatch) {
    const val = parseInt(durationMatch[1], 10);
    durationSeconds = durationMatch[2].toLowerCase().startsWith('m') ? val * 60 : val;
  }

  const parsed = {
    workflowName: 'AI Load Test Journey',
    summary: `Simulating ${virtualUsers} concurrent virtual users across identified endpoint user actions.`,
    virtualUsers,
    rampUpSeconds,
    durationSeconds,
    maxP95LatencyMs: lower.includes('strict') ? 200 : 500,
    maxErrorPercentage: 2.0,
    endpoints: [] as any[]
  };

  // Detect Endpoints or Action Flow from prompt keywords
  if (lower.includes('auth') || lower.includes('login') || lower.includes('sign in') || lower.includes('signin')) {
    parsed.endpoints.push({
      title: 'Auth & Login',
      method: 'POST',
      path: '/api/v1/auth/login',
      body: '{"email":"user@test.com", "password":"password123"}',
      thinkTimeMs: 150
    });
  }

  if (lower.includes('profile') || lower.includes('user') || lower.includes('account')) {
    parsed.endpoints.push({
      title: 'Fetch User Profile',
      method: 'GET',
      path: '/api/v1/user/profile',
      thinkTimeMs: 100
    });
  }

  if (lower.includes('job') || lower.includes('search') || lower.includes('catalog') || lower.includes('product')) {
    parsed.endpoints.push({
      title: 'Search & Fetch Jobs',
      method: 'GET',
      path: '/api/v1/jobs?status=active&limit=50',
      thinkTimeMs: 200
    });
  }

  if (lower.includes('notification') || lower.includes('feed') || lower.includes('dashboard')) {
    parsed.endpoints.push({
      title: 'Fetch User Notifications',
      method: 'GET',
      path: '/api/v1/notifications',
      thinkTimeMs: 100
    });
  }

  // If no specific endpoints detected, generate standard REST user journey
  if (parsed.endpoints.length === 0) {
    parsed.endpoints = [
      {
        title: 'Health Check Ingress',
        method: 'GET',
        path: '/health',
        thinkTimeMs: 50
      },
      {
        title: 'Authenticate User Session',
        method: 'POST',
        path: '/api/auth/session',
        body: '{"grant_type":"password"}',
        thinkTimeMs: 150
      },
      {
        title: 'Fetch Main Feed Data',
        method: 'GET',
        path: '/api/dashboard/feed',
        thinkTimeMs: 200
      }
    ];
  }

  return convertParsedJsonToWorkflow(parsed, baseUrl);
}
